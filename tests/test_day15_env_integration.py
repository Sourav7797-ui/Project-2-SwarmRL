
import numpy as np

from backend.env.config import SwarmEnvConfig
from backend.env.swarm_env import SwarmEnv


def test_environment_uses_voxel_log_reward():
    config = SwarmEnvConfig(
        num_agents=8,
        num_obstacles=8,
        max_episode_steps=64,
        obstacles_move=True,
        obstacle_speed=1.5,
        wind_speed=0.0,
        exploration_reward_mode="voxel_log",
        exploration_voxel_reference=5.0,
    )

    env = SwarmEnv(config=config)

    try:
        env.reset(seed=7000)

        actions = {
            f"drone_{i}": np.zeros(3, dtype=np.float32)
            for i in range(config.num_agents)
        }

        _, rewards, _, _, infos = env.step(actions)

        counts = env._last_new_voxel_counts

        assert counts.shape == (config.num_agents,)
        assert np.all(counts >= 0)

        expected_exploration = (
            np.log1p(counts.astype(np.float32))
            / np.log1p(config.exploration_voxel_reference)
            * config.exploration_reward
        )

        # The reward breakdown is generated by the actual environment step.
        # Verify its exploration contribution through the logger-independent
        # reward calculation using the same step inputs.
        newly_covered = counts > 0

        _, breakdown = env.reward_shaper.compute_with_breakdown(
            newly_covered_by_agent=newly_covered,
            collisions_by_agent=np.zeros(config.num_agents, dtype=bool),
            positions=env.positions,
            world_size_xy=config.world_size_xy,
            world_height=config.world_height,
            obstacle_collisions_by_agent=np.zeros(
                config.num_agents, dtype=bool
            ),
            new_voxel_counts_by_agent=counts,
        )

        np.testing.assert_allclose(
            breakdown["exploration"],
            expected_exploration,
            rtol=1e-6,
        )

        assert len(rewards) == config.num_agents

    finally:
        env.close()
